#!/usr/bin/env python3
"""Progress digest from git history. Deterministic: no model, no network except the optional clone.

Reads each repository listed in progress/repos.txt and prints a markdown digest of commits
and pull requests between two dates, in Africa/Nairobi time.

Pull request numbers come from the commit messages ("Merge pull request #N" and "(#N)").
Open and closed-unmerged pull requests are not in git history, so they are not counted.

Usage:
  python3 scripts/progress.py --since 2026-10-26 --until 2026-11-01 --repos progress/repos.txt --clones .clones --clone
  python3 scripts/progress.py --author 'login|name@example.com' ...   (only your own commits)
  python3 scripts/progress.py --since 2026-11-02 --until 2026-11-08 --repos progress/repos.txt --clones .clones

repos.txt: one repository per line, as  name|clone-url-or-path . Lines starting with # are ignored.
A private list (for example work repositories) can live in a file outside this repository.
"""
import argparse, os, re, subprocess, sys
from collections import defaultdict

TZ = {**os.environ, "TZ": "Africa/Nairobi"}
PR_RE = [re.compile(r"^Merge pull request #(\d+)"), re.compile(r"\(#(\d+)\)\s*$")]

def run(args, cwd=None):
    return subprocess.run(args, cwd=cwd, env=TZ, capture_output=True, text=True, check=True).stdout

def load_repos(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, _, src = line.partition("|")
        out.append((name.strip(), src.strip()))
    return out

def ensure_clone(name, src, clones, do_clone, since):
    if os.path.isdir(src):
        return src
    dest = os.path.join(clones, name)
    if os.path.isdir(dest):
        run(["git", "fetch", "--quiet", "--shallow-since=" + since, "origin"], cwd=dest) if do_clone else None
        return dest
    if not do_clone:
        sys.exit(f"{name}: no clone at {dest}. Re-run with --clone.")
    os.makedirs(clones, exist_ok=True)
    run(["git", "clone", "--quiet", "--shallow-since=" + since, src, dest])
    return dest

def commits(repo_dir, since, until, author=None):
    fmt = "%H%x1f%ad%x1f%an%x1f%P%x1f%s"
    cmd = ["git", "log", "--all", "--no-color", f"--since={since} 00:00", f"--until={until} 23:59:59",
           "--date=format-local:%Y-%m-%d", f"--format={fmt}"]
    if author:
        cmd.append("--author=" + author)  # regex on name and email, e.g. 'MiguelShinyenyi|miguel@example.com'
    out = run(cmd, cwd=repo_dir)
    seen, rows = set(), []
    for line in out.splitlines():
        h, d, a, p, s = line.split("\x1f", 4)
        if h in seen:
            continue
        seen.add(h)
        rows.append({"hash": h, "date": d, "author": a, "merge": len(p.split()) > 1, "subject": s})
    return rows

def pr_numbers(subject):
    for rx in PR_RE:
        m = rx.search(subject)
        if m:
            return int(m.group(1))
    return None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--since", required=True)
    ap.add_argument("--until", required=True)
    ap.add_argument("--repos", default="progress/repos.txt")
    ap.add_argument("--clones", default=".clones")
    ap.add_argument("--clone", action="store_true")
    ap.add_argument("--author", default=None, help="git author regex, matches name or email")
    a = ap.parse_args()

    repos = load_repos(a.repos)
    per_day = defaultdict(lambda: defaultdict(lambda: {"commits": 0, "prs": set(), "subjects": []}))
    totals = {}
    for name, src in repos:
        d = ensure_clone(name, src, a.clones, a.clone, a.since)
        rows = commits(d, a.since, a.until, a.author)
        real = [r for r in rows if not r["merge"]]
        prs = set()
        for r in rows:
            n = pr_numbers(r["subject"])
            if n:
                prs.add(n)
                per_day[r["date"]][name]["prs"].add(n)
        for r in real:
            cell = per_day[r["date"]][name]
            cell["commits"] += 1
            if len(cell["subjects"]) < 3:
                cell["subjects"].append(r["subject"][:80])
        totals[name] = (len(real), len(prs))

    print(f"# Progress {a.since} to {a.until}\n")
    print("Generated by `scripts/progress.py` from git history, Africa/Nairobi dates. "
          "Commits exclude merge commits. Pull request numbers are the merged ones named in commit messages.\n")
    print("## Totals\n")
    print("| Repository | Commits | Merged PRs |\n|---|---|---|")
    for name, _ in repos:
        c, p = totals[name]
        print(f"| {name} | {c} | {p} |")
    print("\n## By day\n")
    print("| Date | Repository | Commits | Merged PRs | Sample of messages |\n|---|---|---|---|---|")
    for day in sorted(per_day):
        for name, _ in repos:
            if name in per_day[day]:
                cell = per_day[day][name]
                prs = ", ".join("#" + str(n) for n in sorted(cell["prs"])) or "none"
                sample = "; ".join(cell["subjects"]).replace("|", "/") or "merge only"
                print(f"| {day} | {name} | {cell['commits']} | {prs} | {sample} |")
    if not per_day:
        print("No commits in this window.")

if __name__ == "__main__":
    main()
